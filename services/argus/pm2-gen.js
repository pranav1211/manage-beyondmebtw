// Argus PM2 ecosystem generation.
//
// Inputs: the authoritative registry entry + the repo declaration's `runtime`
// block. Output: a deterministic `<application>.config.js` text.
//
// Rules: environment is carried by NAME (`envRefs`) only — secret values are
// resolved at reconcile time from the server-private env and never written.
// `cwd` is the server-form deployment path (/projects/<app>); local isolated
// runs translate it at apply time. Output is byte-stable for identical input,
// so a repeat generation produces no Git change.

import { createHash } from 'node:crypto';
import { AppError } from '../../shared/errors.js';
import { validatePm2AppConfig } from '../../shared/schemas/index.js';

const META_PREFIX = '// argus-meta: ';
// Server-side secrets location (Architecture: /infrastructure/env/<app>.env).
export const ENV_ROOT = '/infrastructure/env';
const EXPORT_PREFIX = 'module.exports = ';

export function pm2FileName(application) {
  return `${application}.config.js`;
}

export function buildPm2Metadata(entry, declaration) {
  if (entry.type !== 'node') throw new AppError('VALIDATION_FAILED', 'PM2 config is only generated for node apps');
  const runtime = declaration && declaration.runtime;
  if (!runtime) throw new AppError('VALIDATION_FAILED', 'Node app declaration is missing a runtime block');

  const meta = {
    schemaVersion: 1,
    application: entry.application,
    processes: [
      {
        name: entry.application,
        script: runtime.script,
        cwd: entry.deploymentPath,
        interpreter: 'node',
        execMode: 'fork',
        instances: runtime.instances || 1,
        port: runtime.port,
        envRefs: [...(runtime.envRefs || [])].sort(),
        // Path only — the app loads its own secrets; values never reach Argus/PM2.
        envFile: runtime.envFile ? `${ENV_ROOT}/${entry.application}.env` : null
      }
    ]
  };
  const { valid, errors } = validatePm2AppConfig(meta);
  if (!valid) throw new AppError('VALIDATION_FAILED', 'Generated PM2 metadata is invalid', { errors });
  return meta;
}

function toEcosystem(meta) {
  return {
    apps: meta.processes.map((p) => ({
      name: p.name,
      script: p.script,
      cwd: p.cwd,
      interpreter: p.interpreter || 'node',
      exec_mode: p.execMode,
      instances: p.instances,
      autorestart: true,
      max_restarts: 5,
      ...(p.envFile ? { node_args: [`--env-file=${p.envFile}`] } : {}),
      // Non-secret runtime env only. Secrets: the env file (path above) or
      // argus-meta envRefs — never values here.
      env: { NODE_ENV: 'production', PORT: String(p.port) }
    }))
  };
}

export function renderEcosystem(meta) {
  return [
    '// Generated by Argus — do not edit by hand. Regenerate via Argus.',
    `// application: ${meta.application}`,
    `${META_PREFIX}${JSON.stringify(meta)}`,
    "'use strict';",
    `${EXPORT_PREFIX}${JSON.stringify(toEcosystem(meta), null, 2)};`,
    ''
  ].join('\n');
}

/** Parse + validate a generated file (used on read-back before reconcile). */
export function parseEcosystem(text) {
  const normalized = String(text).replace(/\r\n/g, '\n');
  const metaLine = normalized.split('\n').find((l) => l.startsWith(META_PREFIX));
  if (!metaLine) throw new AppError('INVALID_MANIFEST', 'Generated PM2 file has no argus-meta header');
  let meta;
  try {
    meta = JSON.parse(metaLine.slice(META_PREFIX.length));
  } catch {
    throw new AppError('INVALID_MANIFEST', 'Generated PM2 file has malformed argus-meta');
  }
  const { valid, errors } = validatePm2AppConfig(meta);
  if (!valid) throw new AppError('INVALID_MANIFEST', 'Generated PM2 metadata failed validation', { errors });
  // The body must be exactly what this metadata renders to (no hand edits).
  if (renderEcosystem(meta) !== normalized) {
    throw new AppError('INVALID_MANIFEST', 'Generated PM2 file does not match its metadata (edited by hand?)');
  }
  return { meta, ecosystem: toEcosystem(meta) };
}

export function sha256(text) {
  return createHash('sha256').update(String(text).replace(/\r\n/g, '\n')).digest('hex');
}
